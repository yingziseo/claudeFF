import { expect, test, type Page } from '@playwright/test'

async function enter(page: Page) {
  await page.goto('./')
  await page.getByRole('button', { name: '进入工作空间', exact: true }).click()
  await expect(page.getByRole('heading', { name: '浏览器环境', exact: true })).toBeVisible()
}

test('开发注册和登录直接进入，不发送账号请求', async ({ page }, info) => {
  const writes: string[] = []
  page.on('request', (request) => { if (request.method() !== 'GET') writes.push(request.url()) })
  await page.goto('./')
  await expect(page.getByText('开发模式 · 随意输入即可体验，无需真实账号')).toBeVisible()
  await page.screenshot({ path: info.outputPath('login-dark.png'), fullPage: true })
  await page.getByRole('button', { name: '注册', exact: true }).click()
  await page.getByLabel('用户名').fill('随意输入')
  await page.getByRole('button', { name: '创建并进入工作空间' }).click()
  await expect(page.getByRole('heading', { name: '浏览器环境', exact: true })).toBeVisible()
  await expect(page.locator('.environment-row')).toHaveCount(3)
  await page.screenshot({ path: info.outputPath('environments-dark.png'), fullPage: true })
  expect(writes).toEqual([])
})

test('搜索、空状态和恢复示例可操作', async ({ page }) => {
  await enter(page)
  await page.getByLabel('搜索环境').fill('项目研究')
  await expect(page.locator('.environment-row')).toHaveCount(1)
  await page.getByLabel('搜索环境').fill('找不到的名字')
  await expect(page.getByText('没有找到这个环境')).toBeVisible()
  await page.getByRole('button', { name: '显示全部环境' }).click()
  await expect(page.locator('.environment-row')).toHaveCount(3)
  await page.getByRole('button', { name: '查看空状态' }).click()
  await expect(page.getByRole('button', { name: '创建第一个环境' })).toBeVisible()
  await page.getByRole('button', { name: '重置示例' }).click()
  await expect(page.locator('.environment-row')).toHaveCount(3)
})

test('创建向导隐藏高级参数，并明确没有执行真实检测', async ({ page }, info) => {
  await enter(page)
  await page.getByRole('button', { name: '新建环境' }).click()
  const dialog = page.getByRole('dialog')
  await expect(dialog.getByLabel('代理用户名')).not.toBeVisible()
  await expect(dialog.getByText('当前仅预览流程，不连接代理，也不保存代理凭据。')).toBeVisible()
  await page.screenshot({ path: info.outputPath('create-proxy.png'), fullPage: true })
  await dialog.getByText('高级选项', { exact: true }).click()
  await expect(dialog.getByLabel('代理用户名')).toBeVisible()
  await dialog.getByRole('button', { name: '预览下一步' }).click()
  await dialog.getByLabel('环境名称').fill('前端体验环境')
  await page.screenshot({ path: info.outputPath('create-environment.png'), fullPage: true })
  await dialog.getByRole('button', { name: '添加预览环境' }).click()
  const row = page.locator('.environment-row').filter({ hasText: '前端体验环境' })
  await expect(row.getByText('待检测', { exact: true })).toBeVisible()
  await row.getByRole('button', { name: '启动前端体验环境' }).click()
  await expect(page.getByRole('status')).toContainText('尚未检测')
  await page.getByRole('button', { name: '新建环境' }).click()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog')).not.toBeVisible()
  await expect(page.getByRole('button', { name: '新建环境' })).toBeFocused()
})

test('编辑及删除确认只操作示例数据', async ({ page }) => {
  await enter(page)
  await page.getByRole('button', { name: '编辑项目研究' }).click()
  await page.getByRole('dialog').getByLabel('环境名称').fill('新项目名称')
  await page.getByRole('button', { name: '保存修改' }).click()
  await expect(page.getByRole('heading', { name: '新项目名称' })).toBeVisible()
  await page.getByRole('button', { name: '编辑新项目名称' }).click()
  await page.getByRole('button', { name: '删除环境', exact: true }).click()
  await page.getByRole('button', { name: '保留环境' }).click()
  await expect(page.locator('.environment-row')).toHaveCount(3)
  await page.getByRole('button', { name: '编辑新项目名称' }).click()
  await page.getByRole('button', { name: '删除环境', exact: true }).click()
  await page.getByRole('button', { name: '删除预览环境', exact: true }).click()
  await expect(page.locator('.environment-row')).toHaveCount(2)
})

test('浅色主题可持久化，设置与窄屏布局可用', async ({ page }, info) => {
  await enter(page)
  await page.getByRole('button', { name: '切换为浅色主题' }).click()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'light')
  await page.screenshot({ path: info.outputPath('environments-light.png'), fullPage: true })
  await page.getByRole('button', { name: '设置', exact: true }).click()
  await page.screenshot({ path: info.outputPath('settings-light.png'), fullPage: true })
  await page.reload()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'light')
  await page.getByRole('button', { name: '进入工作空间', exact: true }).click()
  await page.setViewportSize({ width: 375, height: 812 })
  await page.screenshot({ path: info.outputPath('mobile-light.png'), fullPage: true })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.getByRole('button', { name: '设置', exact: true }).click()
  await expect(page.getByRole('heading', { name: '设置', exact: true })).toBeVisible()
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.screenshot({ path: info.outputPath('mobile-settings-light.png'), fullPage: true })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})
